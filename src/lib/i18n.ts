export type Lang = 'en' | 'fr'

/** Bilingual content field. Use with `L(value, lang)`. */
export type Localized<T = string> = { en: T; fr: T }

export function L<T>(v: Localized<T>, lang: Lang): T {
  return v[lang]
}

