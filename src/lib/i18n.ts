const LOCALE = { en: 'en-GB', fr: 'fr-FR' }

export function fmtDate(iso: string, lang: Lang, opts: { year?: boolean } = {}) {
  const d = new Date(iso + 'T12:00:00')
  return d.toLocaleDateString(LOCALE[lang], { day: 'numeric', month: 'short', ...(opts.year === false ? {} : { year: 'numeric' }) })
}
